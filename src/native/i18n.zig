//! Native GUI strings (zh / en).
//!
//! Every user-visible string in the native GUI goes through `StrKey.get()`. Using an enum rather
//! than a runtime dictionary means a missing translation is a *compile* error: both `zh()` and
//! `en()` are exhaustive switches over the same enum, so adding a key without translating it does
//! not build.
//!
//! Composition rule: translated strings never contain format placeholders. Numbers and counts are
//! composed at the call site with a comptime format (`"{s}  {d}"`), because Zig requires format
//! strings to be comptime-known. That also keeps word order free to differ between languages.

const std = @import("std");

pub const Lang = enum {
    zh,
    en,

    pub fn label(self: Lang) [:0]const u8 {
        return switch (self) {
            .zh => "中文",
            .en => "EN",
        };
    }

    /// The string shown on the language button: the language you would switch *to*.
    pub fn other(self: Lang) Lang {
        return switch (self) {
            .zh => .en,
            .en => .zh,
        };
    }
};

