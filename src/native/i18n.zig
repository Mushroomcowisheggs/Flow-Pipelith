test "i18n: every key has both languages and no empty strings" {
    // Zig 0.17's Enum type info exposes field_names/field_values; std.meta.fields is deprecated and
    // the older `fields` slice no longer exists.
    const info = @typeInfo(StrKey).@"enum";
    try std.testing.expect(info.field_names.len > 50);
    // `inline for` keeps the enum values comptime-known (field_values is []const comptime_int, so a
    // runtime loop cannot feed @enumFromInt).
    inline for (info.field_names) |name| {
        const key = @field(StrKey, name);
        const zh = key.get(.zh);
        const en = key.get(.en);
        try std.testing.expect(zh.len > 0);
        try std.testing.expect(en.len > 0);
    }
}
